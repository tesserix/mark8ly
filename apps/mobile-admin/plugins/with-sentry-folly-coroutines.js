// Give the RNSentry pod the Folly defines React Native gives its own pods.
//
// `RNSentryReplay.mm` imports `React/RCTTextView.h`, which transitively pulls
// in Folly's headers. React Native compiles its own pods with
// `-DFOLLY_CFG_NO_COROUTINES=1` (react-native/scripts/cocoapods/helpers.rb),
// and RCT-Folly ships no `folly/coro/` directory at all — so without that
// define Folly decides coroutines are available and reaches for
// `folly/coro/Coroutine.h`, which does not exist:
//
//   'folly/coro/Coroutine.h' file not found
//   ** ARCHIVE FAILED **  (CompileC … RNSentryReplay.o)
//
// RNSentry's own podspec deliberately passes NO Folly flags on React Native
// 0.80+ (`folly_compiler_flags = ''`), on the assumption that the ones it used
// to pass were the incompatible part. For 0.85 the result is that RNSentry is
// the one pod in the workspace compiling Folly with its default config. This
// is unchanged in @sentry/react-native 7.13.0 and 8.28.0, so upgrading does
// not help — the define has to come from here.
//
// A Podfile `post_install` hook is the only seam: pod targets live in the
// generated Pods.xcodeproj, not in the app's own project, so there is nothing
// for `withXcodeProject` to edit. `ios/` is generated by prebuild and is not
// in the repo, which is why this is a plugin rather than a checked-in patch.

const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MARKER = '# sentry-folly-coroutines';

const HOOK = `
  ${MARKER}: RNSentryReplay.mm pulls Folly via React/RCTTextView.h, and
  ${MARKER}: RCT-Folly ships no folly/coro/. Match the define RN uses for its
  ${MARKER}: own pods, or the archive fails on a missing Coroutine.h.
  installer.pods_project.targets.each do |target|
    next unless target.name == 'RNSentry'
    target.build_configurations.each do |config|
      defs = config.build_settings['GCC_PREPROCESSOR_DEFINITIONS'] || ['$(inherited)']
      defs = [defs] unless defs.is_a?(Array)
      defs << 'FOLLY_CFG_NO_COROUTINES=1' unless defs.include?('FOLLY_CFG_NO_COROUTINES=1')
      config.build_settings['GCC_PREPROCESSOR_DEFINITIONS'] = defs
    end
  end
`;

module.exports = function withSentryFollyCoroutines(config) {
  return withDangerousMod(config, [
    'ios',
    (cfg) => {
      const podfile = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      const contents = fs.readFileSync(podfile, 'utf8');

      // Prebuild can run more than once against the same ios/ directory.
      if (contents.includes(MARKER)) return cfg;

      // Append inside the existing `post_install do |installer|` block rather
      // than adding a second one: CocoaPods only honours the last definition,
      // so a second block would silently drop Expo's own post_install work.
      const anchor = /post_install do \|installer\|\n/;
      if (!anchor.test(contents)) {
        throw new Error(
          'with-sentry-folly-coroutines: no `post_install do |installer|` block ' +
            'in the generated Podfile. Expo changed its template — update this ' +
            'plugin rather than removing it, or the iOS archive breaks on a ' +
            "missing folly/coro/Coroutine.h that names Sentry, not this file.",
        );
      }

      fs.writeFileSync(podfile, contents.replace(anchor, (m) => m + HOOK));
      return cfg;
    },
  ]);
};
