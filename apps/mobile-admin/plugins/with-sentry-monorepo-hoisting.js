// Make @sentry/react-native's podspec see THIS app's React Native.
//
// npm hoists `@sentry/react-native` to the monorepo root, and its podspec asks
// node which React Native to build against:
//
//   rn_path = File.dirname(`node --print "require.resolve('react-native/package.json')"`)
//
// CocoaPods evaluates a podspec from the podspec's own directory, so that
// resolves from the ROOT node_modules — where mobile-storefront's React Native
// 0.76.9 lives, not this app's 0.85.3. Everything the podspec decides from the
// version is then decided wrongly:
//
//   should_use_folly_flags(0.76) => true   => passes -DFOLLY_NO_CONFIG, so Folly
//                                             stops reading its config and guesses
//                                             at coroutine support:
//                                             'folly/coro/Coroutine.h' file not found
//   is_new_hermes_runtime(0.76)  => false  => compiles the pre-0.81 Hermes API:
//                                             no member named 'enableSamplingProfiler'
//                                             in 'facebook::hermes::HermesRuntime'
//
// Both surfaced as ** ARCHIVE FAILED ** inside RNSentry, naming Sentry and
// Hermes and Folly — none of which is the actual problem. This is the same
// hoisting bug that broke the Metro bundle (#943) and the jest resolver seven
// times before that; it is the first instance to reach CocoaPods.
//
// `sentry_utils.rb` documents REACT_NATIVE_NODE_MODULES_DIR as the override, so
// set it in the Podfile — which CocoaPods evaluates before it resolves any
// podspec — rather than relying on where npm happened to put the package.
//
// ios/ is generated by prebuild and is not in the repo, hence a config plugin.

const { withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MARKER = '# sentry-monorepo-hoisting';

// Pin the React Native the Sentry podspec resolves. Written as a literal path
// relative to the Podfile rather than a `node --print`, so it cannot pick up
// the same ambient resolution it is here to correct. It fails loudly: a silent
// fallback to the root copy is exactly the outcome this exists to prevent.
const ENV_PIN = `
${MARKER}: @sentry/react-native hoists to the monorepo root and resolves
${MARKER}: react-native from there (0.76.9) instead of this app's 0.85.3,
${MARKER}: which mis-sets its Folly and Hermes flags. See the plugin.
ENV['REACT_NATIVE_NODE_MODULES_DIR'] ||= begin
  dir = File.expand_path('../node_modules/react-native', __dir__)
  raise "REACT_NATIVE_NODE_MODULES_DIR: no react-native at #{dir}" unless File.exist?(File.join(dir, 'package.json'))
  dir
end
`;

// Belt and braces, and independently correct: React Native compiles its own
// pods with -DFOLLY_CFG_NO_COROUTINES=1 and RCT-Folly ships no folly/coro/
// directory. With the version pin above the Sentry podspec stops passing
// -DFOLLY_NO_CONFIG and this should be redundant, but saying it outright costs
// nothing and the failure it prevents is a 12-minute archive.
const FOLLY_HOOK = `
  ${MARKER}: match the Folly define React Native uses for its own pods.
  installer.pods_project.targets.each do |target|
    next unless target.name == 'RNSentry'
    target.build_configurations.each do |config|
      defs = config.build_settings['GCC_PREPROCESSOR_DEFINITIONS'] || ['$(inherited)']
      defs = [defs] unless defs.is_a?(Array)
      defs << 'FOLLY_CFG_NO_COROUTINES=1' unless defs.include?('FOLLY_CFG_NO_COROUTINES=1')
      config.build_settings['GCC_PREPROCESSOR_DEFINITIONS'] = defs
    end
  end
`;

module.exports = function withSentryMonorepoHoisting(config) {
  return withDangerousMod(config, [
    'ios',
    (cfg) => {
      const podfile = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      let contents = fs.readFileSync(podfile, 'utf8');

      // Prebuild can run more than once against the same ios/ directory.
      if (contents.includes(MARKER)) return cfg;

      // The pin has to run before CocoaPods resolves any podspec, so put it at
      // the very top — ahead of the `require`s, which is where the Expo
      // template's own react_native_pods.rb lookups begin.
      contents = ENV_PIN.trimStart() + '\n' + contents;

      // Append inside the existing `post_install do |installer|` block rather
      // than adding a second one: CocoaPods only honours the last definition,
      // so a second block would silently drop Expo's own post_install work.
      const anchor = /post_install do \|installer\|\n/;
      if (!anchor.test(contents)) {
        throw new Error(
          'with-sentry-monorepo-hoisting: no `post_install do |installer|` block ' +
            'in the generated Podfile. Expo changed its template — update this ' +
            'plugin rather than removing it.',
        );
      }
      contents = contents.replace(anchor, (m) => m + FOLLY_HOOK);

      fs.writeFileSync(podfile, contents);
      return cfg;
    },
  ]);
};
